# bit演算 (flagを立てるなど)

# 演算対象のAに対してMと何らかの演算をさせる
A,M=map(int,input().split())

# まとめてflagを立てる
# 2進数で表したMの右からi桁目が1のとき: Aのi番目のflagを立てる
# 　　　　　　　　　　　i桁目が0のとき: そのまま
# A=12       (1100)
# M=5        (0101) 
# output=13  (1101)
print(A|M) 

# まとめてflagを消す
# 2進数で表したMの右からi桁目が1のとき: Aのi番目のflagを消す
# 　　　　　　　　　　　i桁目が0のとき: そのまま
# A=12       (1100)
# M=5        (0101) 
# output=8   (1000)
print(A&~M) 

# まとめてflagを反転する
# 2進数で表したMの右からi桁目が1のとき: Aのi番目のflagを反転
# 　　　　　　　　　　　i桁目が0のとき: そのまま
# A=12       (1100)
# M=5        (0101) 
# output=9   (1001)
print(A^M) 

# 2進数で表したMにおいて1である桁がAにおいて最低1個1であるか否か
# A=12       (1100)
# M=5        (0101) 
# A&M=4      (0100)  0でないので"Yes"  
if A&M:
    print("Yes")
else:
    print("No")

# 2進数で表したMにおいて1である桁がAでも全て1であるか否か
# A=13       (1101)
# M=5        (0101) 
# A&M=4      (0101)  Mと等しいので"Yes"
if A&M==M:
    print("Yes")
else:
    print("No")
    
















